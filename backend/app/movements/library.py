"""The ten movements and everything we measure in each.

IMPORTANT — every target band below is a STARTING POINT drawn from common
coaching guidance and sports-science reading, and every metric is marked
`verified=False` until a qualified coach or physio signs it off. The app shows
an "unverified" note for any score built on unverified metrics. Do not raise
`verified` without a named reviewer in `source`.

Weights add up to 100 inside each movement.
"""
from __future__ import annotations

from app.movements.models import How, Layer, Metric, Movement, Unit

# Shorthand so the data below stays readable.
D, CM, MS, PCT, SPM, DPS = (
    Unit.DEGREES, Unit.CENTIMETRES, Unit.MILLISECONDS,
    Unit.PERCENT, Unit.COUNT_PER_MIN, Unit.DEG_PER_SEC,
)
COACH_REVIEW = "Starting point from general coaching guidance — awaiting coach review"


def M(mid, layer, how, unit, group, name, means, points, moment, lo, hi,
      tol, weight, cue_low, cue_high, cue_good, source=COACH_REVIEW, moment_b=None):
    return Metric(
        id=mid, layer=layer, how=how, unit=unit, group=group, name=name, means=means,
        points=tuple(points), moment=moment, moment_b=moment_b,
        ideal_min=lo, ideal_max=hi, tolerance=tol, weight=weight,
        cue_low=cue_low, cue_high=cue_high, cue_good=cue_good, source=source,
    )


