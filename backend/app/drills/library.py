def for_check(metric_id: str, status: str, limit: int = 3) -> list[Drill]:
    """Drills that fix this check when it is too low or too high."""
    if status not in ("low", "high"):
        return []
    found = [d for d in DRILLS
             if any(m == metric_id and (direction == "any" or direction == status)
                    for m, direction in d.fixes)]
    return found[:limit]


def general(tag: str) -> list[Drill]:
    return [d for d in DRILLS if d.sport == "General" and tag in d.tags]


