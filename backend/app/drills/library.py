"""The drill library: simple drills that fix each measured mistake.

Every check in the measurement library has at least one drill for each way
it can go wrong (too low, too high). A test makes sure that stays true.

Like the checks, every drill is marked unverified until a qualified coach has
signed it off, and the app says so. Drills are deliberately low-risk: body-
weight, shadow swings, light balls, short sets.

`fixes` lists (check id, direction): direction is "low", "high" or "any",
matching the report's status for that check.
`loads` lists the body areas a drill puts work through, so the weekly plan can
go easy on, or leave out, drills that load an area that hurts.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Drill:
    id: str
    name: str
    sport: str                      # sport name, or "General"
    purpose: str                    # one line: what it trains
    steps: tuple[str, ...]
    sets: int
    reps: str                       # "8", "30 seconds", "5 each side"
    equipment: str = "Nothing"
    minutes: int = 5
    loads: tuple[str, ...] = ()
    safety: str | None = None
    fixes: tuple[tuple[str, str], ...] = ()
    verified: bool = False
    tags: tuple[str, ...] = field(default=())


def D(id, name, sport, purpose, steps, sets, reps, *, equipment="Nothing", minutes=5,
      loads=(), safety=None, fixes=(), tags=()):
    return Drill(id, name, sport, purpose, tuple(steps), sets, reps, equipment, minutes,
                 tuple(loads), safety, tuple(fixes), False, tuple(tags))


